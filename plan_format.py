# 기획서 본문(planning_doc)의 공통 형식.
# main.py(기획서 다시 생성·재구성)와 batch_plans.py(배치로 새 기획서 생성)가 같은 형식을 쓰도록 한곳에 둔다.
# 주의: 이 문자열은 프롬프트에 그대로 들어가므로 중괄호({ })를 쓰지 않는다.


def plan_doc_format(max_scenes: int = 4) -> str:
    n = max(1, int(max_scenes))
    return f"""planning_doc는 아래 형식의 마크다운으로 쓴다. 제목 줄 '#'은 쓰지 않는다. '선정 근거', '참조 템플릿', '출처 기사' 섹션은 쓰지 않는다(시스템이 붙인다). 반드시 '## 컨셉'으로 시작한다.

## 컨셉
- **제목**: 기획서 제목
- **형식**: 세로(9:16) 뉴스형 쇼츠, 약 몇 초, 장면 몇 개
- **톤**: 말투와 분위기 한 줄
- **핵심 메시지**: 이 쇼츠가 전하는 사실 1~2문장
- **훅**: 첫 장면에서 시선을 잡는 한 줄

## 구성안
아래 표로 쓴다(헤더 그대로).
| 장면 | 시간 | 화면 | 자막 | 멘트 |
|---|---|---|---|---|
| 1. 훅 | 0~7초 | 화면 묘사 | 자막 한 줄 | 멘트 |
(장면마다 한 줄. 역할 이름은 훅 / 전개 / 공개 / 마무리 등으로 붙인다.)

## 제작 시 주의할 점
- 불릿 3~5개

## 업로드 정보
- **영상 제목 후보**: 1~2개
- **해시태그**: 5~8개(인물·그룹명 포함)

작성 규칙:
- 장면은 {n}개 이하, 장면당 약 6~10초, 전체 45초 이내로 쓴다. 시간 칸은 '0~7초'처럼 쓴다.
- 화면 칸은 한국어로 피사체, 조명, 분위기, 카메라 움직임을 구체적으로 쓴다. 실존 인물(연예인 포함)의 얼굴, 닮은 외모는 묘사하지 말고 무대, 조명, 시상대, 객석, 실루엣, 소품 같은 상징적인 이미지로 표현한다. 화면 안에 글자나 로고를 넣지 않는다.
- 자막 칸은 한 줄 25자 이내로 쓴다. 이름, 순위, 수치는 자막과 멘트로만 전달한다.
- 멘트 칸은 뉴스체 1~2문장으로 쓴다.
- 사실은 기사와 요약에 있는 것만 쓴다. 순위, 수치, 날짜, 기관명을 지어내지 말고, 기사에 없는 것은 '제작 시 주의할 점'에 '확인 필요'로 적는다.
- '제작 시 주의할 점'에는 화면에 얼굴을 쓰지 않는 이유, 글자는 자막으로 넣는다는 점, 출처(발표 기관과 시점) 확인 필요 여부를 반드시 포함한다."""
