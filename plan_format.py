# 기획서 본문(planning_doc)의 공통 형식.
# main.py(기획서 다시 생성·재구성)와 batch_plans.py(배치로 새 기획서 생성)가 같은 형식을 쓰도록 한곳에 둔다.
# 주의: 이 문자열은 프롬프트에 그대로 들어가므로 중괄호({ })를 쓰지 않는다.


def dialogue_rule(target_sec: int = 30) -> str:
    """30초 내외 + 장면별 대사 규칙(프롬프트 문단). main.py와 batch_plans.py가 같이 쓴다."""
    return (f"- 쇼츠 전체 길이는 {int(target_sec)}초 내외로 잡는다. 장면마다 그 장면에서 읽을 대사(내레이션)를 구체적인 문장으로 직접 지어 쓴다. "
            "대사는 기획서의 사실 범위 안에서 새로 만든 구어체 문장이고, 기사에 없는 사실·수치·발언을 지어내서는 안 된다(감정·분위기·응원 표현은 자유롭게 쓴다). "
            "장면 길이에 맞게 대사 길이를 조절하고, 첫 장면은 시선을 끄는 훅 대사로 시작한다.\n")


def fan_plan_rule(celeb: str = "") -> str:
    """연예인 카테고리 기획서: 덕후(팬) 말투 + 결말 응원 멘트 규칙. 이름이 없으면 '해당 연예인'."""
    name = " ".join(str(celeb or "").split())[:50] or "해당 연예인"
    return (f"- 이 기획서는 '연예인' 카테고리다. 대사 전체를 {name}를 좋아하는 팬(덕후)의 말투로 쓰고, 영상의 결말(마무리 구간)에는 {name}에 대한 애정과 응원의 한마디를 반드시 넣는다. "
            "구성안의 마무리 행 멘트에 그 응원 문장을 구체적으로 적고, 팬의 진심이 느껴지는 따뜻하고 친근한 말투로 쓴다. "
            "응원은 감정 표현으로만 쓰고 기사에 없는 사실을 지어내지 마라(예: 앞으로도 응원한다, 건강하길 바란다). "
            "사건·사고·논란·부고처럼 가벼운 응원이 어색한 이슈이면 들뜬 말투를 쓰지 말고 차분하고 정중하게 마음을 전하는 정도로 톤을 낮추며, 한쪽 편을 들거나 당사자를 감싸는 표현은 쓰지 마라.\n")


def plan_doc_format(max_scenes: int = 4) -> str:
    n = max(1, int(max_scenes))
    return f"""planning_doc는 아래 형식의 마크다운으로 쓴다. 제목 줄 '#'은 쓰지 않는다. '선정 근거', '참조 템플릿', '출처 기사' 섹션은 쓰지 않는다(시스템이 붙인다). 반드시 '## 컨셉'으로 시작한다.

## 컨셉
- **제목**: 기획서 제목
- **형식**: 세로(9:16) 쇼츠, 약 30초, 장면 몇 개
- **톤**: 말투와 분위기 한 줄
- **핵심 메시지**: 이 쇼츠가 전하는 사실 1~2문장
- **훅**: 첫 장면에서 시선을 잡는 한 줄

## 구성안
아래 표로 쓴다(헤더 그대로).
| 장면 | 시간 | 화면 | 자막 | 멘트 |
|---|---|---|---|---|
| 1. 훅 | 0~5초 | 화면 묘사 | 자막 한 줄 | 멘트 |
(장면마다 한 줄. 역할 이름은 훅 / 전개 / 공개 / 마무리 등으로 붙인다.)

## 제작 시 주의할 점
- 불릿 3~5개

## 업로드 정보
- **영상 제목 후보**: 1~2개
- **해시태그**: 5~8개(인물·그룹명 포함)

작성 규칙:
- 장면은 {n}개 이하, 장면당 약 5~6초, 전체 30초 내외(25~35초)로 쓴다. 시간 칸은 '0~5초'처럼 쓴다.
- 화면 칸은 한국어로 피사체, 조명, 분위기, 카메라 움직임을 구체적으로 쓴다. 실존 인물(연예인 포함)의 얼굴, 닮은 외모는 묘사하지 말고 무대, 조명, 시상대, 객석, 실루엣, 소품 같은 상징적인 이미지로 표현한다. 화면 안에 글자나 로고를 넣지 않는다.
- 자막 칸은 한 줄 25자 이내로 쓴다. 이름, 순위, 수치는 자막과 멘트로만 전달한다.
- 멘트 칸은 그 장면에서 소리 내어 읽을 대사 1~2문장이다. 톤에 정한 말투의 자연스러운 구어체로 직접 지어 쓰고, 장면 길이(약 5~6초, 공백 포함 25~35자)에 맞춘다. 첫 장면은 훅 대사로 시작한다. 대사에 쓰는 사실은 기사와 요약에 있는 것으로 한정하고 말투·감정·응원 표현만 새로 지어 쓴다.
- 사실은 기사와 요약에 있는 것만 쓴다. 순위, 수치, 날짜, 기관명을 지어내지 말고, 기사에 없는 것은 '제작 시 주의할 점'에 '확인 필요'로 적는다.
- '제작 시 주의할 점'에는 화면에 얼굴을 쓰지 않는 이유, 글자는 자막으로 넣는다는 점, 출처(발표 기관과 시점) 확인 필요 여부를 반드시 포함한다."""
